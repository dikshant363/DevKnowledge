import re
from typing import List

from apps.api.app.compiler.ckr import CKRDocument


class MarkdownCompiler:
    """Compiles CKR document into clean, versioned Markdown with provenance frontmatter."""

    @staticmethod
    def compile(doc: CKRDocument) -> str:
        lines = [
            "---",
            f'title: "{doc.title}"',
            f'source_url: "{doc.canonical_url}"',
            f'path: "{doc.normalized_path}"',
            f'version: "{doc.source_version or "latest"}"',
            f'content_hash: "{doc.content_hash}"',
            f'extracted_at: "{doc.extracted_at.isoformat()}"',
            "---",
            "",
            f"# {doc.title}",
            "",
        ]

        # Deprecation notice banner if any symbols are deprecated
        deprecated = [s for s in doc.api_symbols if s.is_deprecated]
        if deprecated:
            lines.append("> [!WARNING]")
            lines.append("> **Deprecation Alert:** This document mentions deprecated APIs:")
            for dep in deprecated:
                lines.append(f"> - `{dep.name}`: {dep.signature}")
            lines.append("")

        for section in doc.sections:
            if section.heading and section.heading.lower() != doc.title.lower():
                hashes = "#" * max(2, min(6, section.level))
                lines.append(f"{hashes} {section.heading}")
                lines.append("")
            if section.content:
                lines.append(section.content)
                lines.append("")

        if doc.code_snippets:
            lines.append("## Code Examples")
            lines.append("")
            for i, snip in enumerate(doc.code_snippets):
                desc = f"### Example {i + 1}" + (
                    f": {snip.description}" if snip.description else ""
                )
                lines.append(desc)
                lines.append(f"```{snip.language}")
                lines.append(snip.code)
                lines.append("```")
                lines.append("")

        if doc.api_symbols:
            lines.append("## API Reference")
            lines.append("")
            for sym in doc.api_symbols:
                dep_marker = " *(deprecated)*" if sym.is_deprecated else ""
                lines.append(f"### `{sym.name}`{dep_marker}")
                lines.append(f"```text\n{sym.signature}\n```")
                if sym.description:
                    lines.append(sym.description)
                lines.append("")

        return "\n".join(lines).strip() + "\n"


class LLMsTxtCompiler:
    """Compiles documentation overview conforming to the llms.txt standard."""

    @staticmethod
    def compile(source_name: str, root_url: str, docs: List[CKRDocument]) -> str:
        lines = [
            f"# {source_name}",
            "",
            f"> Official technical documentation for {source_name}.",
            f"> Canonical URL: {root_url}",
            "",
            "## Documentation Index",
            "",
        ]

        for doc in sorted(docs, key=lambda d: d.normalized_path):
            desc = (
                doc.sections[0].content[:150].replace("\n", " ")
                if doc.sections
                else "Documentation page"
            )
            lines.append(f"- [{doc.title}]({doc.canonical_url}): {desc}...")

        lines.append("")
        lines.append("## Optional Files")
        lines.append("")
        lines.append(
            f"- [llms-full.txt]({root_url.rstrip('/')}/llms-full.txt): Complete combined documentation"
        )
        lines.append(
            f"- [AGENTS.md]({root_url.rstrip('/')}/AGENTS.md): Coding agent conventions and API rules"
        )

        return "\n".join(lines).strip() + "\n"


class LLMsFullTxtCompiler:
    """Compiles all documents into a single llms-full.txt representation."""

    @staticmethod
    def compile(source_name: str, docs: List[CKRDocument]) -> str:
        lines = [
            f"# {source_name} — Complete Documentation",
            "",
            f"> Generated by DevKnowledge Knowledge Compiler. Total pages: {len(docs)}.",
            "",
            "=" * 60,
            "",
        ]

        for doc in docs:
            lines.append(f"<!-- START PAGE: {doc.title} ({doc.canonical_url}) -->")
            lines.append(MarkdownCompiler.compile(doc))
            lines.append(f"<!-- END PAGE: {doc.title} -->")
            lines.append("")
            lines.append("-" * 40)
            lines.append("")

        return "\n".join(lines).strip() + "\n"


class AgentsMdCompiler:
    """Compiles AGENTS.md instructions for autonomous coding agents."""

    @staticmethod
    def compile(source_name: str, docs: List[CKRDocument]) -> str:
        lines = [
            f"# AGENTS.md — {source_name} Knowledge Contract",
            "",
            "> Instructions and API rules extracted from official documentation.",
            "> coding agents MUST follow these conventions when writing software using this framework.",
            "",
            "## 1. Verified Architecture & APIs",
            "",
        ]

        all_symbols = []
        for d in docs:
            all_symbols.extend(d.api_symbols)

        if all_symbols:
            lines.append(f"Discovered {len(all_symbols)} API symbols in official documentation:")
            for sym in all_symbols[:30]:
                lines.append(f"- `{sym.name}`: `{sym.signature}`")
            if len(all_symbols) > 30:
                lines.append(f"- ... and {len(all_symbols) - 30} more symbols.")
            lines.append("")

        # Collect deprecations
        deprecated = [s for s in all_symbols if s.is_deprecated]
        if deprecated:
            lines.append("## 2. Deprecated APIs (DO NOT USE)")
            lines.append("")
            for dep in deprecated:
                lines.append(f"- ⚠️ **`{dep.name}`**: `{dep.signature}`")
            lines.append("")

        lines.append("## 3. General Implementation Rules")
        lines.append("")
        lines.append("1. Always reference the official canonical URL for each API.")
        lines.append("2. Never invent or hallucinate functions not listed in this documentation.")
        lines.append("3. Match parameter types strictly as documented.")

        return "\n".join(lines).strip() + "\n"


class SkillMdCompiler:
    """Compiles reusable, task-specific SKILL.md files from documented workflows."""

    @staticmethod
    def compile(task_name: str, doc: CKRDocument) -> str:
        skill_name = re.sub(r"[^a-z0-9]+", "-", task_name.lower()).strip("-")

        lines = [
            "---",
            f"name: {skill_name}",
            f'description: "How to {task_name} based on official documentation from {doc.canonical_url}"',
            "---",
            "",
            f"# {task_name}",
            "",
            "## Context",
            f"Derived from official documentation: [{doc.title}]({doc.canonical_url})",
            "",
            "## Prerequisites & Installation",
            "",
        ]

        # Extract code snippet if available
        if doc.code_snippets:
            lines.append("```" + doc.code_snippets[0].language)
            lines.append(doc.code_snippets[0].code)
            lines.append("```")
            lines.append("")

        lines.append("## Step-by-Step Procedure")
        lines.append("")
        for i, sec in enumerate(doc.sections):
            lines.append(f"{i + 1}. **{sec.heading}**")
            lines.append(f"   {sec.content[:200]}...")
            lines.append("")

        lines.append("## Verification")
        lines.append("- Ensure all types match the documented API signatures.")
        lines.append("- Verify no deprecated methods were called.")

        return "\n".join(lines).strip() + "\n"
